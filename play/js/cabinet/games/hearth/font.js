const ADV = 6;

export function textWidth(text, h, track = 0) { const s = h / 6; return Math.max(0, String(text).length * (ADV + track) - 2 - track) * s; }

export function drawText(batch, text, x, y, o = {}) {
  const h = o.h ?? 20, s = h / 6, track = o.track ?? 0, color = o.color ?? [1.2, 0.4, 0.02], style = o.style;
  const w = textWidth(text, h, track);
  let x0 = o.align === 'left' ? x : o.align === 'right' ? x - w : x - w / 2;
  for (const ch of String(text)) {
    const g = G[ch] ?? G[ch.toUpperCase()];
    if (g) for (const stroke of g) batch.line(stroke.map(([gx, gy]) => [x0 + gx * s, y + gy * s]), color, style);
    x0 += (ADV + track) * s;
  }
  return w;
}
