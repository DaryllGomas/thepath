// ------------------------------------------------------------------ parsing
export const Tile = Object.freeze({ Floor: 0, Wall: 1, Door: 2, Exit: 3 });
export const Item = Object.freeze({ None: 0, Key: 1, Food: 2, Jug: 3, Potion: 4, Chest: 5 });
export const Mon = Object.freeze({ Ghost: 0, Brute: 1, Imp: 2, Warlock: 3, Wraith: 4 });
export const MonNames = Object.freeze(['GHOST', 'BRUTE', 'IMP', 'WARLOCK', 'WRAITH']);

const ITEM_OF = { k: Item.Key, f: Item.Food, j: Item.Jug, p: Item.Potion, $: Item.Chest };
const GEN_OF = { G: Mon.Ghost, B: Mon.Brute, I: Mon.Imp, W: Mon.Warlock };
const MON_OF = { g: Mon.Ghost, b: Mon.Brute, i: Mon.Imp, w: Mon.Warlock, R: Mon.Wraith };

// a level as plain arrays: tiles, torches, items, generators, monsters, start, exit
export function parseLevel(def) {
    const rows = def.map, H = rows.length, W = rows[0].length;
    for (let y = 0; y < H; y++) if (rows[y].length !== W) throw new Error(def.name + ': row ' + y + ' is ' + rows[y].length + ' wide, not ' + W);
    const L = {
        name: def.name, hint: def.hint, feature: def.feature, pace: def.pace, stone: def.stone || ['wl', 'fl'], W, H,
        tile: new Uint8Array(W * H), torch: new Uint8Array(W * H), item: new Uint8Array(W * H),
        gens: [], mons: [], sx: 1, sy: 1, ex: 1, ey: 1, keys: 0, doors: 0,
    };
    for (let y = 0; y < H; y++)
        for (let x = 0; x < W; x++) {
            const c = rows[y][x], i = y * W + x;
            const edge = x === 0 || y === 0 || x === W - 1 || y === H - 1;
            if (edge && c !== '#' && c !== 't') throw new Error(def.name + ': open edge at ' + x + ',' + y);
            if (c === '#' || c === 't') { L.tile[i] = Tile.Wall; if (c === 't') L.torch[i] = 1; continue; }
            if (c === 'D') { L.tile[i] = Tile.Door; L.doors++; continue; }
            if (c === 'E') { L.tile[i] = Tile.Exit; L.ex = x; L.ey = y; continue; }
            L.tile[i] = Tile.Floor;
            if (c === 'S') { L.sx = x; L.sy = y; }
            else if (ITEM_OF[c] !== undefined) { L.item[i] = ITEM_OF[c]; if (c === 'k') L.keys++; }
            else if (GEN_OF[c] !== undefined) L.gens.push({ type: GEN_OF[c], tx: x, ty: y });
            else if (MON_OF[c] !== undefined) L.mons.push({ type: MON_OF[c], tx: x, ty: y });
            else if (c !== '.') throw new Error(def.name + ': unknown map char ' + c + ' at ' + x + ',' + y);
        }
    return L;
}
