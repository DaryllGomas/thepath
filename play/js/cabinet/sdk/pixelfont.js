// THE NODE · CABINET ENGINE (JS) · the three bitmap fonts every cabinet shares (port of Core/PixelFont.cs,
// glyph data bit for bit).
//
//   PixelFont.Arcade   5x7, advance 6: the Grid Cycles / PixelCanvas font (+ punctuation). Body text, plates.
//   PixelFont.Small    3x5, advance 4: fine print only (credit line, tiny legends).
//   PixelFont.Display  7x7 in an 8x8 cell, advance 8: bold, Namco-style. Titles and big HUD digits (scale 2).
//
// Glyph rows run top to bottom; within a row the leftmost column is the highest bit (bit cellW-1).
// Lower case draws as upper case. Space and unknown characters advance only.
// One addition over Staging/CabinetSDK/Core: '&' in all three fonts (Batch3 mudmetal's Core edit),
// so that port needs no font change. Grid Cycles never draws it.

export class PixelFont {
    constructor(name, cellW, cellH, advance, lineHeight) {
        this.name = name; this.cellW = cellW; this.cellH = cellH; this.advance = advance; this.lineHeight = lineHeight;
        this._glyphs = new Map();
    }

    static _norm(c) { const k = c.charCodeAt(0); return k >= 97 && k <= 122 ? String.fromCharCode(k - 32) : c; }

    has(c) { return c === ' ' || this._glyphs.has(PixelFont._norm(c)); }

    glyph(c) { const g = this._glyphs.get(PixelFont._norm(c)); return g === undefined ? null : g; }

    get chars() { return [...this._glyphs.keys()]; }

    // the width a string covers at this scale (no trailing gap)
    measure(s, scale = 1) {
        if (!s) return 0;
        return (s.length * this.advance - (this.advance - this.cellW)) * scale;
    }

    height(scale = 1) { return this.cellH * scale; }

    _addHex(c, ...rows) { this._glyphs.set(c, Uint8Array.from(rows)); }

    _addRows(c, ...rows) {
        const b = new Uint8Array(this.cellH);
        for (let r = 0; r < this.cellH && r < rows.length; r++) {
            let v = 0;
            for (let col = 0; col < this.cellW && col < rows[r].length; col++)
                if (rows[r][col] === '#') v |= 1 << (this.cellW - 1 - col);
            b[r] = v;
        }
        this._glyphs.set(c, b);
    }
}

